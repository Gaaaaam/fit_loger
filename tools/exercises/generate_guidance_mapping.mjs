import { mkdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { parseArgs } from 'node:util';
import { loadGuidanceManifest } from './guidance_prompt.mjs';

function main() {
  const { values } = parseArgs({ options: {
    manifest: { type: 'string' }, media: { type: 'string' }, out: { type: 'string' }
  } });
  for (const field of ['manifest', 'media', 'out']) {
    if (!values[field]) throw new Error(`--${field} is required`);
  }
  const entries = loadGuidanceManifest(values.manifest).filter(entry => entry.status === 'approved');
  const q = value => JSON.stringify(value);
  const rows = entries.map(entry => {
    const resources = gender => Array.from({ length: entry.frameCount }, (_, index) => {
      const name = `ex_${entry.id}_${gender}_${String(index + 1).padStart(2, '0')}`;
      const path = join(values.media, `${name}.webp`);
      if (!statSync(path).isFile()) throw new Error(`missing frame: ${path}`);
      return `$r('app.media.${name}')`;
    }).join(', ');
    return `  { id: ${q(entry.id)}, femaleFrames: [${resources('female')}], maleFrames: [${resources('male')}], ` +
      `frameCaptions: ${q(entry.captions)}, cardFrameIndex: ${entry.cardFrameIndex} }`;
  });
  const source = `export interface GeneratedGuidanceArtwork {
  id: string;
  femaleFrames: Resource[];
  maleFrames: Resource[];
  frameCaptions: string[];
  cardFrameIndex: number;
}

// Generated by tools/exercises/generate_guidance_mapping.mjs; do not edit manually.
export const GENERATED_GUIDANCE_ARTWORK: GeneratedGuidanceArtwork[] = [${rows.length ? '\n' + rows.join(',\n') + '\n' : ''}];
`;
  mkdirSync(dirname(values.out), { recursive: true });
  writeFileSync(values.out, source, 'utf8');
  console.log(`Generated ${entries.length} approved guidance entries`);
}

try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
